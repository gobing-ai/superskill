/**
 * Generate native Pi hook extensions from a plugin's canonical hooks.json (ADR-039).
 *
 * Pi has no declarative hooks: its extension API (`pi.on(event, handler)`) is the hook surface.
 * Instead of the `@vahor/pi-hooks` shim — which can only run a command and block on exit 2 — this
 * generator writes one self-contained extension module per declared hook into Pi's auto-discovered
 * extensions dir (`~/.pi/agent/extensions/` global, `<project>/.pi/extensions/` project). Each
 * module spawns the hook command with `SUPERSKILL_HOOK_HOST=pi` and `SUPERSKILL_HOOK_EVENT`, so
 * `superskill hook run` hands back the script's host-neutral decision, which the module applies
 * with Pi's own primitives:
 *
 * | Canonical event | Pi event | deny / block | ask |
 * | --- | --- | --- | --- |
 * | PreToolUse | `tool_call` | `{ block: true, reason }` | `ctx.ui.confirm`; no UI → block |
 * | PostToolUse | `tool_result` | reason appended to the tool result content | allow |
 * | Stop | `agent_end` | `pi.sendMessage(reason, { deliverAs: 'followUp', triggerTurn: true })` continues the run | allow |
 * | UserPromptSubmit | `input` | `{ action: 'handled' }` + notify | allow |
 * | SessionStart / SessionEnd / PreCompact | `session_start` / `session_shutdown` / `session_before_compact` | notify only (not vetoable) | allow |
 *
 * Verified against `@earendil-works/pi-coding-agent@1.2.0` (`dist/core/extensions/types.d.ts`,
 * `docs/extensions.md`); the same surface still works on `@earendil-works/pi-coding-agent@0.85.1`.
 * Ownership: every module carries the superskill banner and a `// Plugin: <plugin>` header; a reinstall removes that plugin's modules first, and the plugin's
 * legacy shim entries in Pi's `hooks.json` are pruned so a hook never runs twice.
 */

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parseCommandArgv } from './command-argv';
import {
    applyHookTargetPolicy,
    type CanonicalHooksConfig,
    type EmitHooksOptions,
    type EmitHooksResult,
    flattenCanonicalHookEntries,
    hookRunKey,
    type PiHookEntry,
    readCanonicalHooks,
    reconcileOwnedHookEvents,
} from './hooks';
import piHookExtensionTemplate from './templates/pi-hook-extension.txt' with { type: 'text' };

/** Canonical (camelCase) hook event → the Pi extension event its generated module subscribes to. */
export const PI_NATIVE_HOOK_EVENTS: Partial<Record<string, string>> = {
    preToolUse: 'tool_call',
    postToolUse: 'tool_result',
    stop: 'agent_end',
    userPromptSubmit: 'input',
    // rulesync's canonical name for Claude's UserPromptSubmit (the mapper renames it on install).
    beforeSubmitPrompt: 'input',
    sessionStart: 'session_start',
    sessionEnd: 'session_shutdown',
    preCompact: 'session_before_compact',
};

/** Marker line every generated module carries; ownership pruning keys on it. */
export const PI_HOOK_BANNER = '// Generated by superskill install — do not edit manually.';

/** Outer deadline when hooks.json declares no `timeout` (Claude Code's default, 60 s). */
const DEFAULT_TIMEOUT_MS = 60_000;

/** Result of {@link emitPiNativeHooks}: an {@link EmitHooksResult} plus the module paths. */
export interface PiHookResult extends EmitHooksResult {
    /** Generated module paths (would-be paths in dry-run). */
    files: string[];
}

interface ParsedPiHook {
    piEvent: string;
    canonicalEvent: string;
    matcher: string;
    command: string;
    timeout?: number;
    name: string;
}

function parsePiHooks(config: CanonicalHooksConfig): ParsedPiHook[] {
    const parsed: ParsedPiHook[] = [];
    for (const [rawEvent, definitions] of Object.entries(config.hooks ?? {})) {
        const camel = rawEvent.charAt(0).toLowerCase() + rawEvent.slice(1);
        const piEvent = PI_NATIVE_HOOK_EVENTS[camel];
        if (!piEvent) continue;
        for (const entry of flattenCanonicalHookEntries(definitions)) {
            if ((entry.type && entry.type !== 'command') || !entry.command) continue;
            parsed.push({
                piEvent,
                canonicalEvent:
                    camel === 'beforeSubmitPrompt'
                        ? 'UserPromptSubmit'
                        : camel.charAt(0).toUpperCase() + camel.slice(1),
                matcher: entry.matcher,
                command: entry.command,
                timeout: entry.timeout,
                name: hookModuleStem(entry.command),
            });
        }
    }
    return parsed;
}

/**
 * Filename-safe stem for a hook command: the hook id of `superskill hook run`, else the last
 * token's basename without its extension (`bash ./scripts/check.sh` → `check`), else `hook`.
 */
function hookModuleStem(command: string): string {
    const key = hookRunKey(command);
    const last = parseCommandArgv(command).pop() ?? '';
    const raw = key ? (key.split('/')[1] ?? '') : (last.split('/').pop() ?? '').replace(/\.[^.]*$/, '');
    return raw.replace(/[^a-zA-Z0-9_-]/g, '') || 'hook';
}

/** Build one extension module's source from {@link piHookExtensionTemplate}. */
export function buildPiHookModule(plugin: string, hook: ParsedPiHook): string {
    // Comment interpolations stay on one line — a newline would escape the `//` comment.
    const oneLine = (s: string) => s.replace(/[\r\n]+/g, ' ');
    const replacements: Record<string, string> = {
        '%%PLUGIN_COMMENT%%': oneLine(plugin),
        '%%EVENT%%': hook.piEvent,
        '%%CANONICAL_EVENT_COMMENT%%': hook.canonicalEvent,
        '%%MATCHER_COMMENT%%': hook.matcher === '*' ? '*' : oneLine(hook.matcher),
        '%%COMMAND_COMMENT%%': oneLine(hook.command),
        '%%EVENT_LITERAL%%': JSON.stringify(hook.piEvent),
        '%%CANONICAL_EVENT_LITERAL%%': JSON.stringify(hook.canonicalEvent),
        '%%MATCHER_LITERAL%%': hook.matcher === '*' || hook.matcher === '' ? 'null' : JSON.stringify(hook.matcher),
        '%%COMMAND_LITERAL%%': JSON.stringify(hook.command),
        '%%TIMEOUT_MS%%': String(hook.timeout ? hook.timeout * 1000 : DEFAULT_TIMEOUT_MS),
        '%%LABEL_LITERAL%%': JSON.stringify(`${plugin}/${hook.name}`),
    };
    // Single pass: inserted values are never re-scanned for sentinel tokens.
    return piHookExtensionTemplate.replace(/%%[A-Z_]+%%/g, (token) => replacements[token] ?? token);
}

/** Pi's extensions dir for the scope: `<root>/.pi/agent/extensions` (global) or `<root>/.pi/extensions`. */
export function piExtensionsDir(outputRoot: string, global: boolean): string {
    return global ? join(outputRoot, '.pi', 'agent', 'extensions') : join(outputRoot, '.pi', 'extensions');
}

/** The generated modules in `dir` that `plugin` owns (superskill banner + `// Plugin: <plugin>`). */
export function listPiHookModules(dir: string, plugin: string): string[] {
    if (!existsSync(dir)) return [];
    const owned: string[] = [];
    for (const entry of readdirSync(dir)) {
        if (!entry.endsWith('.ts')) continue;
        const filePath = join(dir, entry);
        try {
            const content = readFileSync(filePath, 'utf-8');
            if (!content.includes(PI_HOOK_BANNER)) continue;
            if (content.match(/^\/\/ Plugin: (.+)$/m)?.[1]?.trim() === plugin) owned.push(filePath);
        } catch {
            // unreadable entry (a directory, a permission error): not ours to touch
        }
    }
    return owned;
}

/** Remove the generated modules `plugin` owns from `dir`; returns the removed paths. */
export function prunePiHookModules(dir: string, plugin: string): string[] {
    const owned = listPiHookModules(dir, plugin);
    for (const filePath of owned) rmSync(filePath, { force: true });
    return owned;
}

/**
 * Drop `plugin`'s entries from the legacy `@vahor/pi-hooks` config (`<root>/.pi/agent/hooks.json`
 * global, `<root>/.pi/hooks.json` project) so an install that switched to native modules does not
 * run the same hook twice. Other plugins' and user entries are kept; an absent or unparseable file
 * is left alone. Returns true when the file was rewritten.
 */
export function prunePiShimHooks(outputRoot: string, global: boolean, plugin: string): boolean {
    const hooksPath = global ? join(outputRoot, '.pi', 'agent', 'hooks.json') : join(outputRoot, '.pi', 'hooks.json');
    if (!existsSync(hooksPath)) return false;
    let raw: { hooks?: unknown; [k: string]: unknown };
    try {
        raw = JSON.parse(readFileSync(hooksPath, 'utf-8'));
    } catch {
        return false;
    }
    if (!raw || typeof raw.hooks !== 'object' || raw.hooks === null) return false;
    const existing = raw.hooks as Record<string, PiHookEntry[]>;
    const commandOf = (entry: PiHookEntry): string => (typeof entry === 'string' ? entry : entry.command);
    const pruned = reconcileOwnedHookEvents(
        existing,
        {},
        {
            pruneOwned: (entry) => (hookRunKey(commandOf(entry)).startsWith(`${plugin}/`) ? undefined : entry),
            signature: commandOf,
        },
    );
    if (JSON.stringify(pruned) === JSON.stringify(existing)) return false;
    writeFileSync(hooksPath, `${JSON.stringify({ ...raw, hooks: pruned }, null, 2)}\n`);
    return true;
}

/**
 * Emit `plugin`'s hooks as native Pi extension modules (see the module doc). Reads
 * `<rulesyncDir>/hooks.json`, applies the per-target policy for `pi`, removes the plugin's previous
 * modules and legacy shim entries, then writes `superskill-<plugin>-<hook>.ts` per hook. Names are
 * deterministic: a repeated stem gets `-2`, `-3`, … in canonical order. Dry-run writes nothing.
 */
export function emitPiNativeHooks(
    rulesyncDir: string,
    outputRoot: string,
    options: EmitHooksOptions,
    plugin: string,
): PiHookResult {
    const dir = piExtensionsDir(outputRoot, options.global);
    const config = readCanonicalHooks(rulesyncDir);
    if (!config?.hooks) {
        return { target: 'pi', emitted: false, count: 0, files: [], message: 'pi: no hooks in plugin' };
    }
    const hooks = parsePiHooks(applyHookTargetPolicy(config, 'pi'));
    if (!options.dryRun) {
        prunePiHookModules(dir, plugin);
        prunePiShimHooks(outputRoot, options.global, plugin);
    }
    const files: string[] = [];
    const used = new Set<string>();
    for (const hook of hooks) {
        const base = `superskill-${plugin.replace(/[^a-zA-Z0-9_-]/g, '')}-${hook.name}`;
        let stem = base;
        for (let ordinal = 2; used.has(stem); ordinal++) stem = `${base}-${ordinal}`;
        used.add(stem);
        const filePath = join(dir, `${stem}.ts`);
        if (!options.dryRun) {
            mkdirSync(dir, { recursive: true });
            writeFileSync(filePath, buildPiHookModule(plugin, hook));
        }
        files.push(filePath);
    }
    if (files.length === 0) {
        return { target: 'pi', emitted: false, count: 0, files, path: dir, message: 'pi: no mappable hooks' };
    }
    return {
        target: 'pi',
        emitted: true,
        count: files.length,
        files,
        path: dir,
        message: `pi: ${files.length} hook(s) emitted as native extension module(s) in ${dir}`,
    };
}
